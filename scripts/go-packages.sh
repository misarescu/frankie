#!/usr/bin/env bash
# Lists the non-standard Go packages Frankie's builds, tests and lint import
# (with the build tags lint uses), for the dependency image's warm-up to
# pre-compile (M3.1, `mise run deps:warm`). Written by `mise run generate`.
set -euo pipefail
cd "$(dirname "$0")/.."

out=go-packages.txt
{
	echo "# Generated by scripts/go-packages.sh (mise run generate); do not edit."
	{
		go list -deps -test -f '{{if not .Standard}}{{.ImportPath}}{{end}}' ./...
		go list -tags e2e,smoke,record -deps -test -f '{{if not .Standard}}{{.ImportPath}}{{end}}' ./...
	} | grep -v '^github.com/misarescu/frankie' | LC_ALL=C sort -u
} > "$out.tmp"
mv "$out.tmp" "$out"
